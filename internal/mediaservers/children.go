// Ports are the listeners of the two servers. The four internal ones are on the loopback address and reached by
// StreamGo alone; the three media ports are reached by browsers.
type Ports struct {
	LiveKit    int // LiveKit's signalling and API
	WHIP       int // MediaMTX's WebRTC (WHIP) HTTP server
	RTSP       int
	API        int // MediaMTX's control API
	LiveKitTCP int
	LiveKitUDP int
	WebRTC     int // MediaMTX's WebRTC media, UDP and TCP
}

// Credentials are what the server and the two media servers share. They reach a child only in its environment.
type Credentials struct {
	LiveKitKey, LiveKitSecret  string
	MediaMTXUser, MediaMTXPass string
}

// Setup is everything the two children are built from.
type Setup struct {
	Dir         string // <data_dir>/media: the generated configuration goes there
	NodeIP      string // the address both servers advertise
	Ports       Ports
	Credentials Credentials
	Environ     []string // the parent's environment (os.Environ)
}

const generated = "# Generated by streamgo up at every start from its flags; it holds no secret. Changes here are lost.\n"

// liveKitYAML follows packaging/livekit.yaml; the key and secret come from LIVEKIT_KEYS, the address from --node-ip.
const liveKitYAML = `port: %d
bind_addresses: [127.0.0.1]
rtc:
  tcp_port: %d
  udp_port: %d
  use_external_ip: false
room:
  auto_create: false
logging:
  level: info
`

// mediaMTXYAML follows packaging/mediamtx.yml; the user and password come from MTX_AUTHINTERNALUSERS_0_*, the
// advertised address from MTX_WEBRTCADDITIONALHOSTS.
const mediaMTXYAML = `logLevel: info

authMethod: internal
authInternalUsers:
  - user: streamgo
    pass: ""
    ips: []
    permissions:
      - action: publish
      - action: read
      - action: api

api: true
apiAddress: 127.0.0.1:%d
metrics: false
pprof: false
playback: false

rtsp: true
rtspTransports: [tcp]
rtspEncryption: "no"
rtspAddress: 127.0.0.1:%d

rtmp: false
hls: false
srt: false
moq: false

webrtc: true
webrtcAddress: 127.0.0.1:%d
webrtcLocalUDPAddress: :%d
webrtcLocalTCPAddress: :%d
webrtcIPsFromInterfaces: false
webrtcAdditionalHosts: []
webrtcICEServers2: []

pathDefaults:
  source: publisher
paths:
  all_others:
`

// Children writes the configuration of the two servers under s.Dir and returns them ready to start, LiveKit
// first. Ready is left to the caller.
func Children(s Setup, liveKit, mediaMTX Program) ([]Child, error) {
	p, c := s.Ports, s.Credentials
	lkConf := filepath.Join(s.Dir, "livekit.yaml")
	if err := writeFile(lkConf, generated+fmt.Sprintf(liveKitYAML, p.LiveKit, p.LiveKitTCP, p.LiveKitUDP)); err != nil {
		return nil, err
	}
	mtxConf := filepath.Join(s.Dir, "mediamtx.yml")
	if err := writeFile(mtxConf, generated+fmt.Sprintf(mediaMTXYAML, p.API, p.RTSP, p.WHIP, p.WebRTC, p.WebRTC)); err != nil {
		return nil, err
	}
	// LiveKit reads LIVEKIT_KEYS as YAML: JSON is YAML, and keeps any key and secret a string
	keys, err := json.Marshal(map[string]string{c.LiveKitKey: c.LiveKitSecret})
	if err != nil {
		return nil, fmt.Errorf("LiveKit keys: %w", err)
	}
	base := BaseEnv(s.Environ)
	return []Child{
		{
			Name: "livekit", Path: liveKit.Path,
			Args: []string{"--config", lkConf, "--node-ip", s.NodeIP},
			Env:  append(base, "LIVEKIT_KEYS="+string(keys)),
		},
		{
			Name: "mediamtx", Path: mediaMTX.Path,
			Args: []string{mtxConf},
			Env: append(BaseEnv(s.Environ),
				"MTX_AUTHINTERNALUSERS_0_USER="+c.MediaMTXUser, "MTX_AUTHINTERNALUSERS_0_PASS="+c.MediaMTXPass,
				"MTX_WEBRTCADDITIONALHOSTS="+s.NodeIP, "MTX_WEBRTCIPSFROMINTERFACES=false"),
		},
	}, nil
}

// BaseEnv is the part of the parent's environment a child gets: PATH, HOME, TZ and the locale variables.
func BaseEnv(environ []string) []string {
	var out []string
	hasPath := false
	for _, kv := range environ {
		name, _, _ := strings.Cut(kv, "=")
		switch {
		case name == "PATH":
			hasPath = true
			out = append(out, kv)
		case name == "HOME", name == "TZ", name == "LANG", name == "LANGUAGE", strings.HasPrefix(name, "LC_"):
			out = append(out, kv)
		}
	}
	if !hasPath {
		out = append(out, "PATH=/usr/local/bin:/usr/bin:/bin")
	}
	return out
}

func writeFile(path, text string) error {
	return writeAtomic(path, 0o600, func(w io.Writer) error {
		_, err := io.WriteString(w, text)
		return err
	})
}

// FreePorts returns n distinct TCP ports free on the loopback address at this moment, none of them one of exclude
// (the ports this instance will listen on itself).
func FreePorts(ctx context.Context, n int, exclude ...int) ([]int, error) {
	var lc net.ListenConfig
	return freePorts(n, exclude, func() (net.Listener, error) { return lc.Listen(ctx, "tcp", "127.0.0.1:0") })
}

func freePorts(n int, exclude []int, listen func() (net.Listener, error)) ([]int, error) {
	var ports []int
	for tries := 0; len(ports) < n; tries++ {
		if tries > n+64 {
			return nil, errors.New("choose a free port: the system keeps offering excluded ports")
		}
		l, err := listen()
		if err != nil {
			return nil, fmt.Errorf("choose a free port: %w", err)
		}
		defer func() { _ = l.Close() }() // held until all are chosen: never offered twice
		if p := l.Addr().(*net.TCPAddr).Port; !slices.Contains(exclude, p) {
			ports = append(ports, p)
		}
	}
	return ports, nil
}

// MediaPort is a port browsers reach, with the flag that sets it.
type MediaPort struct {
	Network string // tcp or udp
	Port    int
	Flag    string
}

// CheckMediaPorts fails, naming the flag, when a media port is already in use.
func CheckMediaPorts(ctx context.Context, ports []MediaPort) error {
	var lc net.ListenConfig
	var errs []error
	for _, p := range ports {
		addr := ":" + strconv.Itoa(p.Port)
		var err error
		if p.Network == "udp" {
			var c net.PacketConn
			if c, err = lc.ListenPacket(ctx, "udp", addr); err == nil {
				_ = c.Close()
			}
		} else {
			var l net.Listener
			if l, err = lc.Listen(ctx, "tcp", addr); err == nil {
				_ = l.Close()
			}
		}
		if err != nil {
			errs = append(errs, fmt.Errorf("port %d/%s is in use: free it or choose another with %s", p.Port, p.Network, p.Flag))
		}
	}
	return errors.Join(errs...)
}

// NodeIP is the IPv4 address of the default route, else 127.0.0.1. dial is net.Dial; a UDP "connection" sends
// nothing, it only picks the route.
func NodeIP(dial func(network, addr string) (net.Conn, error)) string {
	c, err := dial("udp4", "192.0.2.1:9")
	if err != nil {
		return "127.0.0.1"
	}
	defer func() { _ = c.Close() }()
	if a, ok := c.LocalAddr().(*net.UDPAddr); ok && a.IP.To4() != nil && !a.IP.IsUnspecified() {
		return a.IP.String()
	}
	return "127.0.0.1"
}
